export interface BimtekModule {
  id: string;
  title: string;
  category: string;
  pkb: number;
  duration: string;
  level: string;
}

type ModuleSeed = [id: string, title: string, pkb: number, duration: string, level: string];

function group(category: string, modules: ModuleSeed[]): BimtekModule[] {
  return modules.map(([id, title, pkb, duration, level]) => ({
    id,
    title,
    category,
    pkb,
    duration,
    level,
  }));
}

